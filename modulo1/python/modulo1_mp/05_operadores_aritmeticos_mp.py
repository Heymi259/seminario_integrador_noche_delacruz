# Calculadora de entrenamiento NovaFit

peso = float(input("Ingrese el peso levantado (kg): "))
repeticiones = float(input("Ingrese el número de repeticiones: "))

print("=== NovaFit Gym ===")

print("Suma")
print(f"{peso} + {repeticiones} = {peso + repeticiones}")

print("Resta")
print(f"{peso} - {repeticiones} = {peso - repeticiones}")

print("Multiplicación")
print(f"{peso} * {repeticiones} = {peso * repeticiones}")

print("División")
print(f"{peso} / {repeticiones} = {peso / repeticiones}")

print("Módulo")
print(f"{peso} % {repeticiones} = {peso % repeticiones}")

print("Exponente")
print(f"{peso} ** {repeticiones} = {peso ** repeticiones}")