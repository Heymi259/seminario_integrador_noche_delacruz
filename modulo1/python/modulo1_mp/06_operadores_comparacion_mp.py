print("=== Comparación de Datos - NovaFit ===")

peso_actual = float(input("Ingrese el peso actual del socio (kg): "))
peso_objetivo = float(input("Ingrese el peso objetivo del socio (kg): "))

print(peso_actual, "==", peso_objetivo, ":", peso_actual == peso_objetivo)
print(peso_actual, "!=", peso_objetivo, ":", peso_actual != peso_objetivo)
print(peso_actual, ">", peso_objetivo, ":", peso_actual > peso_objetivo)
print(peso_actual, "<", peso_objetivo, ":", peso_actual < peso_objetivo)
print(peso_actual, ">=", peso_objetivo, ":", peso_actual >= peso_objetivo)
print(peso_actual, "<=", peso_objetivo, ":", peso_actual <= peso_objetivo)